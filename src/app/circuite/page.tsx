"use client";
import { Fragment, useMemo, useState } from "react";
import { RequireProject } from "@/components/shell/AppShell";
import { CATEGORY_LABEL, circuitOptions, roomLabel } from "@/components/install/common";
import { Badge, Button, Card, Code, ConfirmButton, Empty, NumberInput, PageHeader, Select, Table, TextInput, TrackedNumber, cx } from "@/components/ui";
import { allCircuitLoads, generateCircuits, moveDevice, type CircuitLoad, type GenerationReport } from "@/lib/engine/circuits";
import { isPowerDevice } from "@/lib/engine/power";
import { fmtNum, NA } from "@/lib/format";
import { newCircuit, removeCircuit } from "@/lib/model/factory";
import type { Circuit, PhaseAssign, Project } from "@/lib/model/types";
import { useActiveProject, useUpdateActive } from "@/lib/store/store";

type Up = ReturnType<typeof useUpdateActive>;

function CircuitsPage() {
  const p = useActiveProject()!;
  const up = useUpdateActive();
  const [report, setReport] = useState<GenerationReport | null>(null);
  const [open, setOpen] = useState<Set<string>>(new Set());
  const loads = useMemo(() => allCircuitLoads(p), [p]);
  const unassigned = p.devices.filter((d) => !d.circuitId && d.category !== "curenti_slabi");
  const totalPi = loads.reduce((s, l) => s + (l.installed.value ?? 0), 0);
  const totalPa = loads.reduce((s, l) => s + (l.appliedW ?? 0), 0);

  const phases = useMemo(() => {
    const m: Record<string, number> = { L1: 0, L2: 0, L3: 0 };
    for (const l of loads) {
      const ph = l.circuit.phase;
      const w = l.appliedW ?? 0;
      if (ph === "L123") (["L1", "L2", "L3"] as const).forEach((k) => (m[k] += w / 3));
      else if (ph) m[ph] += w;
    }
    return m;
  }, [loads]);
  const maxPh = Math.max(phases.L1, phases.L2, phases.L3);
  const minPh = Math.min(phases.L1, phases.L2, phases.L3);
  const imbalance = maxPh > 0 ? ((maxPh - minPh) / maxPh) * 100 : 0;

  const run = (mode: "completeaza" | "reorganizeaza") => {
    let rep: GenerationReport | null = null;
    up((x) => void (rep = generateCircuits(x, mode)), mode === "completeaza" ? "Generare circuite pentru punctele neasociate" : "Reorganizare automata circuite");
    setReport(rep);
  };

  return (
    <div className="space-y-4">
      <PageHeader
        title="Circuite"
        subtitle="Propunerea automata grupeaza punctele dupa destinatie, incapere/nivel si un buget de putere (conventia R011, editabila). Orice punct poate fi mutat manual; mutarile manuale se pastreaza la regenerare."
        actions={
          <>
            <Button variant="primary" onClick={() => run("completeaza")} disabled={unassigned.filter((d) => d.category !== "intrerupator").length === 0}>
              Genereaza pentru punctele neasociate
            </Button>
            <ConfirmButton size="md" label="Reorganizeaza (pastreaza mutarile manuale)" onConfirm={() => run("reorganizeaza")}>Reorganizeaza automat…</ConfirmButton>
            <Button onClick={() => up((x) => void x.circuits.push(newCircuit(x, "Circuit nou", "prize", "ctp-prize", false)), "Circuit manual adaugat")}>+ Circuit manual</Button>
          </>
        }
      />

      {report && (
        <div className="rounded-md border border-line bg-white px-4 py-2 text-sm">
          Asociate <b>{report.assigned}</b> puncte · circuite noi: <b>{report.created.join(", ") || "—"}</b>
          {report.removed.length > 0 && <> · eliminate (goale): {report.removed.join(", ")}</>}
          <button className="ml-3 text-xs text-ink-3 underline" onClick={() => setReport(null)}>inchide</button>
        </div>
      )}

      <div className="grid gap-3 md:grid-cols-4">
        <Stat label="Circuite" value={String(p.circuits.length)} sub={`${p.circuits.filter((c) => c.autoGenerated).length} automate · ${p.circuits.filter((c) => !c.autoGenerated).length} manuale`} />
        <Stat label="Putere instalata (Σ circuite)" value={fmtNum(totalPi / 1000) + " kW"} />
        <Stat label="Putere aplicata (Σ P x ks)" value={fmtNum(totalPa / 1000) + " kW"} sub="inainte de simultaneitatea globala" />
        {p.supply.system === "tri" ? (
          <Stat
            label="Repartizare pe faze (P aplicata)"
            value={`${fmtNum(phases.L1 / 1000, 1)} / ${fmtNum(phases.L2 / 1000, 1)} / ${fmtNum(phases.L3 / 1000, 1)} kW`}
            sub={<span className={cx(imbalance > (p.library.rules.find((r) => r.id === "r-echilibrare")?.params.maxImbalancePct ?? 20) && "text-warn")}>dezechilibru {fmtNum(imbalance, 0)}%</span>}
          />
        ) : (
          <Stat label="Puncte neasociate" value={String(unassigned.length)} sub={unassigned.length ? "vezi lista de mai jos" : "toate punctele au circuit"} />
        )}
      </div>

      {p.circuits.length === 0 ? (
        <Empty title="Nu exista circuite">Adauga puncte in Doze si aparate, apoi apasa „Genereaza pentru punctele neasociate”.</Empty>
      ) : (
        <Table>
          <thead>
            <tr>
              <th>Cod</th>
              <th>Denumire</th>
              <th>Tip</th>
              <th className="num">Puncte</th>
              <th className="num">P inst.</th>
              <th className="num">ks</th>
              <th className="num">P apl.</th>
              <th className="num" title="curent de calcul pentru puterea aplicata">Ic</th>
              <th>Cablu</th>
              <th>Protectie</th>
              <th>Pozare</th>
              <th className="num">Lungime</th>
              <th>Faza</th>
              <th />
            </tr>
          </thead>
          <tbody>
            {loads.map((l, i) => (
              <Fragment key={l.circuit.id}>
                <CircuitRow
                  p={p}
                  l={l}
                  up={up}
                  first={i === 0}
                  last={i === loads.length - 1}
                  open={open.has(l.circuit.id)}
                  toggle={() => setOpen((s) => { const n = new Set(s); if (n.has(l.circuit.id)) n.delete(l.circuit.id); else n.add(l.circuit.id); return n; })}
                />
                {open.has(l.circuit.id) && <CircuitDetails p={p} l={l} up={up} />}
              </Fragment>
            ))}
            <tr className="bg-paper font-semibold">
              <td colSpan={4}>Total</td>
              <td className="num whitespace-nowrap">{fmtNum(totalPi, 0)} W</td>
              <td />
              <td className="num whitespace-nowrap">{fmtNum(totalPa, 0)} W</td>
              <td colSpan={7} />
            </tr>
          </tbody>
        </Table>
      )}

      {unassigned.length > 0 && (
        <Card title={`Puncte neasociate (${unassigned.length})`} subtitle="Intrerupatoarele se asociaza automat circuitului lampii pe care o comanda.">
          <Table>
            <thead><tr><th>Cod</th><th>Categorie</th><th>Eticheta</th><th>Incapere</th><th className="num">Putere</th><th>Muta pe circuit</th></tr></thead>
            <tbody>
              {unassigned.map((d) => (
                <tr key={d.id}>
                  <td><Code>{d.code}</Code></td>
                  <td className="text-xs">{CATEGORY_LABEL[d.category]}</td>
                  <td>{d.label}</td>
                  <td className="text-xs">{roomLabel(p, d.roomId)}</td>
                  <td className="num">{isPowerDevice(d) ? (d.powerW.value === null ? <span className="v-unknown">{NA}</span> : `${d.powerW.value} W`) : "—"}</td>
                  <td className="w-64"><Select value={null} placeholder="alege circuit…" onChange={(v) => up((x) => moveDevice(x, d.id, v || null), `${d.code} asociat manual`)} options={circuitOptions(p)} /></td>
                </tr>
              ))}
            </tbody>
          </Table>
        </Card>
      )}
    </div>
  );
}

function Stat({ label, value, sub }: { label: string; value: string; sub?: React.ReactNode }) {
  return (
    <div className="rounded-lg border border-line bg-white p-3">
      <p className="text-[11px] font-semibold uppercase tracking-wide text-ink-2">{label}</p>
      <p className="mt-0.5 text-lg font-semibold tabular-nums">{value}</p>
      {sub && <p className="text-xs text-ink-2">{sub}</p>}
    </div>
  );
}

function CircuitRow({ p, l, up, first, last, open, toggle }: { p: Project; l: CircuitLoad; up: Up; first: boolean; last: boolean; open: boolean; toggle: () => void }) {
  const c = l.circuit;
  const lib = p.library;
  const set = (recipe: (x: Circuit) => void, h?: string) => up((x) => { const y = x.circuits.find((z) => z.id === c.id); if (y) recipe(y); }, h);
  const move = (dir: -1 | 1) =>
    up((x) => {
      const list = [...x.circuits].sort((a, b) => a.order - b.order);
      const i = list.findIndex((z) => z.id === c.id);
      const j = i + dir;
      if (j < 0 || j >= list.length) return;
      [list[i], list[j]] = [list[j], list[i]];
      list.forEach((z, k) => (z.order = k));
      x.circuits = list;
    });
  const protections = lib.protectionDevices.filter((d) => d.kind === "MCB" || d.kind === "RCBO");
  const fromRoutes = p.cables.some((cb) => cb.circuitId === c.id);
  const ib = l.designCurrentA;
  const overIn = ib !== null && c.protection.ratingA !== null && ib > c.protection.ratingA;
  const pts = [l.sockets && `${l.sockets} P`, l.lights && `${l.lights} IL`, l.switches && `${l.switches} I`, l.others && `${l.others} A`].filter(Boolean).join(" · ");

  return (
    <tr className={cx(open && "bg-volt/5")}>
      <td>
        <button onClick={toggle} className="font-mono text-[12px] font-semibold hover:underline" title="Detalii si puncte">
          {open ? "▾" : "▸"} {c.code}
        </button>
        {!c.autoGenerated && <div className="text-[10px] text-ink-3">manual</div>}
      </td>
      <td className="min-w-48"><TextInput value={c.name} onChange={(v) => set((x) => void (x.name = v))} /></td>
      <td className="min-w-36">
        <Select
          value={c.circuitTypeId}
          placeholder="—"
          onChange={(v) => set((x) => { x.circuitTypeId = v || null; const t = lib.circuitTypes.find((k) => k.id === v); if (t) x.usage = t.usage; })}
          options={lib.circuitTypes.map((t) => ({ value: t.id, label: t.name }))}
        />
      </td>
      <td className="num whitespace-nowrap text-xs">{pts || "—"}</td>
      <td className="num whitespace-nowrap">
        <span className={cx(l.installed.unknownCount > 0 && "v-estimated")} title={l.installed.unknownCount ? `${l.installed.unknownCount} consumatori fara putere` : undefined}>
          {l.installed.value === null ? NA : fmtNum(l.installed.value, 0) + " W"}
        </span>
      </td>
      <td className="w-20"><NumberInput value={c.simultaneity.value} onChange={(v) => set((x) => void (x.simultaneity = { value: v === null ? null : Math.min(1, Math.max(0, v)), provenance: "estimat", status: "estimat" }))} /></td>
      <td className="num whitespace-nowrap font-semibold">{l.appliedW === null ? <span className="v-unknown">{NA}</span> : fmtNum(l.appliedW, 0) + " W"}</td>
      <td className={cx("num whitespace-nowrap", overIn && "font-semibold text-red-700")} title={l.installedCurrentA !== null ? `la puterea instalata integral: ${fmtNum(l.installedCurrentA)} A` : undefined}>
        {ib === null ? NA : fmtNum(ib, 1) + " A"}
      </td>
      <td className="min-w-32">
        <Select value={c.cableTypeId} placeholder="de stabilit" onChange={(v) => set((x) => void (x.cableTypeId = v || null))} options={lib.cableTypes.map((t) => ({ value: t.id, label: t.name }))} />
      </td>
      <td className="min-w-40">
        <Select
          value={c.protection.protectionDeviceId}
          placeholder="de stabilit"
          onChange={(v) =>
            set((x) => {
              const d = lib.protectionDevices.find((k) => k.id === v);
              x.protection = { ...x.protection, protectionDeviceId: v || null, ratingA: d?.ratingA ?? null, curve: d?.curve ?? null, poles: d?.poles ?? x.protection.poles };
            })
          }
          options={protections.map((d) => ({ value: d.id, label: `${d.kind} ${d.curve ?? ""}${d.ratingA ?? ""} ${d.poles} - ${d.brand}` }))}
        />
      </td>
      <td className="w-20">
        <Select value={c.installMethodId} placeholder="—" onChange={(v) => set((x) => void (x.installMethodId = v || null))} options={lib.installMethods.map((m) => ({ value: m.id, label: m.ref }))} />
      </td>
      <td className="min-w-32">
        {fromRoutes ? (
          <span className={cx("block text-right tabular-nums", l.length.certainty === "masurat" ? "v-measured" : "v-estimated")} title="din trasee + rezerva">
            {l.length.value === null ? NA : fmtNum(l.length.value, 1) + " m"} <span className="text-[10px] text-ink-3">trasee</span>
          </span>
        ) : (
          <TrackedNumber value={c.estimatedLengthM} suffix="m" allowedProvenance={["estimat", "masurat"]} onChange={(v) => set((x) => void (x.estimatedLengthM = v))} />
        )}
      </td>
      <td className="w-20">
        {p.supply.system === "mono" ? (
          <span className="text-xs">L1</span>
        ) : (
          <Select<PhaseAssign> value={c.phase} placeholder="—" onChange={(v) => set((x) => void (x.phase = v || null))} options={["L1", "L2", "L3", "L123"].map((v) => ({ value: v as PhaseAssign, label: v === "L123" ? "3F" : v }))} />
        )}
      </td>
      <td className="whitespace-nowrap text-right">
        <Button size="sm" variant="ghost" disabled={first} onClick={() => move(-1)} title="muta sus">↑</Button>
        <Button size="sm" variant="ghost" disabled={last} onClick={() => move(1)} title="muta jos">↓</Button>
        <ConfirmButton label="Sterge circuitul" onConfirm={() => up((x) => removeCircuit(x, c.id), `Circuit sters ${c.code}`)}>✕</ConfirmButton>
      </td>
    </tr>
  );
}

function CircuitDetails({ p, l, up }: { p: Project; l: CircuitLoad; up: Up }) {
  const c = l.circuit;
  const set = (recipe: (x: Circuit) => void) => up((x) => { const y = x.circuits.find((z) => z.id === c.id); if (y) recipe(y); });
  const others = circuitOptions(p).filter((o) => o.value !== c.id);
  return (
    <tr className="bg-paper">
      <td />
      <td colSpan={13} className="py-3">
        <div className="mb-2 flex flex-wrap gap-2">
          {l.warnings.map((w) => <Badge key={w} tone="warn">{w}</Badge>)}
          {l.designCurrentA !== null && c.protection.ratingA !== null && l.designCurrentA > c.protection.ratingA && <Badge tone="bad">Ic depaseste In al protectiei</Badge>}
          <Badge tone="info">verificarile Ic ≤ I&apos;z, ΔU si coordonarea protectiei vin in etapa 3</Badge>
        </div>
        {l.devices.length === 0 ? (
          <p className="text-sm text-ink-3">Niciun punct pe acest circuit.</p>
        ) : (
          <table className="dense w-full border-collapse text-sm">
            <thead><tr><th>Cod</th><th>Categorie</th><th>Eticheta</th><th>Incapere</th><th>Doza</th><th className="num">Putere</th><th>Muta pe</th></tr></thead>
            <tbody>
              {l.devices.map((d) => (
                <tr key={d.id}>
                  <td><Code>{d.code}</Code> {d.circuitLocked && <Badge tone="info">manual</Badge>}</td>
                  <td className="text-xs">{CATEGORY_LABEL[d.category]}</td>
                  <td>{d.label}</td>
                  <td className="text-xs">{roomLabel(p, d.roomId)}</td>
                  <td className="font-mono text-xs">{p.boxes.find((b) => b.id === d.boxId)?.code ?? "—"}</td>
                  <td className="num">{isPowerDevice(d) ? (d.powerW.value === null ? <span className="v-unknown">{NA}</span> : `${d.powerW.value} W`) : "—"}</td>
                  <td className="w-60"><Select value={null} placeholder="alt circuit…" onChange={(v) => up((x) => moveDevice(x, d.id, v || null), `${d.code} mutat manual`)} options={[...others, { value: "", label: "— elibereaza" }]} /></td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
        <div className="mt-3 grid gap-3 md:grid-cols-4">
          <label className="text-xs">
            <span className="mb-1 block font-semibold uppercase tracking-wide text-ink-2">Temperatura ambianta</span>
            <NumberInput value={c.ambientTempC} suffix="°C" onChange={(v) => set((x) => void (x.ambientTempC = v ?? 30))} />
          </label>
          <label className="text-xs">
            <span className="mb-1 block font-semibold uppercase tracking-wide text-ink-2">Circuite grupate (K2)</span>
            <NumberInput value={c.groupedCircuits} onChange={(v) => set((x) => void (x.groupedCircuits = Math.max(1, v ?? 1)))} />
          </label>
          <label className="text-xs md:col-span-2">
            <span className="mb-1 block font-semibold uppercase tracking-wide text-ink-2">Observatii</span>
            <TextInput value={c.notes} onChange={(v) => set((x) => void (x.notes = v))} />
          </label>
        </div>
      </td>
    </tr>
  );
}

export default function Page() {
  return (
    <RequireProject>
      <CircuitsPage />
    </RequireProject>
  );
}
