import { describe, expect, it } from "vitest";
import { createDefaultLibrary } from "@/lib/library/default-library";
import { applyTemplate, createEmptyProject, tracked } from "@/lib/model/factory";
import { allocateCode, formatCode, takeCode, uid } from "@/lib/model/ids";
import { roomArea, roomPerimeter, routeLength, chaseLength, sumQty } from "@/lib/engine/measure";
import { availablePower, installedPower, appliedPower, designCurrent } from "@/lib/engine/power";
import { computeLabor, computeMaterials, computeTotals } from "@/lib/engine/pricing";
import { computeSummary } from "@/lib/engine/summary";
import { parseImport, projectToFile, libraryToFile, projectAsTemplate } from "@/lib/io/files";
import type { Box, Circuit, Device, Project, Route } from "@/lib/model/types";

const lib = () => createDefaultLibrary();
const proj = () => {
  const p = createEmptyProject(lib());
  applyTemplate(p, p.library.templates.find((t) => t.id === "tpl-casa-pe")!);
  return p;
};
const box = (p: Project, kind: "DA" | "DD", roomId: string, boxTypeId: string): Box => ({
  id: uid(), code: takeCode(p.counters, kind), kind, roomId, boxTypeId, modules: 2, position: "", heightCm: null, status: "estimat", notes: "",
});
const device = (p: Project, roomId: string, category: Device["category"], powerW: number | null, circuitId: string | null = null, boxId: string | null = null): Device => ({
  id: uid(), code: takeCode(p.counters, category === "iluminat" ? "IL" : "AP"), deviceTypeId: null, category, roomId, boxId, label: "", modules: 1,
  powerW: tracked(powerW, "proiectant"), threePhase: false, circuitId, lightingTopology: "direct", controlledByIds: [], status: "estimat", notes: "",
});
const circuit = (p: Project, ks: number | null, usage: Circuit["usage"] = "prize"): Circuit => ({
  id: uid(), code: takeCode(p.counters, "CI"), name: "test", circuitTypeId: null, usage, panelId: null, phase: "L1", cableTypeId: "ct-fy3x25", installMethodId: "im-b1",
  protection: { protectionDeviceId: null, ratingA: 16, curve: "C", poles: "1P+N", rcdItemId: null }, simultaneity: tracked(ks), estimatedLengthM: tracked(20),
  ambientTempC: 30, groupedCircuits: 1, autoGenerated: false, lockedFields: [], order: 0, status: "estimat", notes: "",
});

describe("identificatori", () => {
  it("format doua litere + trei cifre", () => {
    expect(formatCode("DA", 1)).toBe("DA001");
    expect(formatCode("CI", 42)).toBe("CI042");
  });
  it("nu reutilizeaza coduri dupa stergere", () => {
    const c: Record<string, number> = {};
    const a = takeCode(c, "DA");
    takeCode(c, "DA");
    // stergem primul element - contorul ramane
    expect(a).toBe("DA001");
    expect(takeCode(c, "DA")).toBe("DA003");
    expect(takeCode(c, "DD")).toBe("DD001");
  });
  it("allocateCode este pur", () => {
    const c = { CI: 5 };
    const r = allocateCode(c, "CI");
    expect(r.code).toBe("CI006");
    expect(c.CI).toBe(5);
  });
});

describe("incaperi", () => {
  it("suprafata si perimetru calculate", () => {
    const p = proj();
    const r = p.rooms[0];
    r.lengthM = tracked(4);
    r.widthM = tracked(2.5);
    expect(roomArea(r).value).toBe(10);
    expect(roomPerimeter(r).value).toBe(13);
    expect(roomArea(r).certainty).toBe("estimat");
    r.lengthM = tracked(4, "masurat");
    r.widthM = tracked(2.5, "masurat");
    expect(roomArea(r).certainty).toBe("masurat");
  });
  it("dimensiune lipsa => necunoscut, nu zero", () => {
    const p = proj();
    const r = p.rooms[0];
    r.widthM = tracked<number>(null);
    expect(roomArea(r).value).toBeNull();
  });
  it("sablonul creeaza niveluri si incaperi", () => {
    const p = proj();
    expect(p.levels.map((l) => l.name)).toEqual(["Parter", "Etaj 1"]);
    expect(p.rooms.length).toBe(11);
    expect(p.rooms[0].code).toBe("IN001");
  });
});

describe("puteri", () => {
  it("putere disponibila mono 230V x 32A = 7,36 kVA", () => {
    const p = proj();
    p.supply.mainBreakerA = tracked(32, "beneficiar");
    const a = availablePower(p);
    expect(a.fromBreakerKVA).toBe(7.36);
    expect(a.basis).toBe("protectie");
  });
  it("putere disponibila tri 400V x 25A", () => {
    const p = proj();
    p.supply.system = "tri";
    p.supply.voltageV = 400;
    p.supply.mainBreakerA = tracked(25);
    expect(availablePower(p).fromBreakerKVA).toBe(17.32);
  });
  it("putere necunoscuta fara date", () => {
    expect(availablePower(proj()).effectiveKW).toBeNull();
  });
  it("puterea instalata ignora curentii slabi si raporteaza necunoscutele", () => {
    const p = proj();
    const r = p.rooms[0].id;
    p.devices.push(device(p, r, "priza", 2000), device(p, r, "priza", null), device(p, r, "curenti_slabi", null));
    const ip = installedPower(p);
    expect(ip.value).toBe(2000);
    expect(ip.unknownCount).toBe(1);
  });
  it("puterea aplicata cu simultaneitate pe circuit si date insuficiente", () => {
    const p = proj();
    const r = p.rooms[0].id;
    const c1 = circuit(p, 0.5);
    const c2 = circuit(p, null);
    p.circuits.push(c1, c2);
    p.devices.push(device(p, r, "priza", 2000, c1.id), device(p, r, "priza", 1000, c2.id));
    const ap = appliedPower(p);
    expect(ap.value).toBe(1000);
    expect(ap.insufficient).toBe(true);
  });
  it("curent de calcul", () => {
    expect(designCurrent(3500, "mono", 1, 230)).toBe(15.22);
  });
});

describe("trasee si sant comun", () => {
  it("santul comun se numara o singura data", () => {
    const p = proj();
    const c1 = circuit(p, 1);
    const c2 = circuit(p, 1);
    p.circuits.push(c1, c2);
    const route: Route = {
      id: uid(), code: takeCode(p.counters, "TR"), name: "Hol", roomIds: [p.rooms[0].id], surface: "perete", requiresChase: true, wallTypeId: null,
      segments: [
        { id: uid(), from: { kind: "free", refId: null, label: "TA" }, to: { kind: "free", refId: null, label: "DD" }, lengthM: tracked(6, "masurat"), wallTypeId: null, notes: "" },
        { id: uid(), from: { kind: "free", refId: null, label: "DD" }, to: { kind: "free", refId: null, label: "DA" }, lengthM: tracked(4), wallTypeId: null, notes: "" },
      ],
      conduits: [
        { id: uid(), code: takeCode(p.counters, "CP"), conduitTypeId: "cd-20", lengthOverrideM: null, circuitIds: [c1.id] },
        { id: uid(), code: takeCode(p.counters, "CP"), conduitTypeId: "cd-20", lengthOverrideM: null, circuitIds: [c2.id] },
      ],
      parentRouteId: null, status: "estimat", notes: "",
    };
    p.routes.push(route);
    expect(routeLength(route).value).toBe(10);
    expect(routeLength(route).certainty).toBe("partial");
    expect(chaseLength(p).value).toBe(10);
    const s = computeSummary(p);
    expect(s.lengths.conduit.value).toBe(20);
    const sant = computeLabor(p).lines.find((l) => l.operation.id === "op-sant")!;
    expect(sant.quantity).toBe(10);
  });
  it("suma cu valori lipsa raporteaza lipsa", () => {
    const q = sumQty([{ value: 2, certainty: "estimat", missing: 0 }, { value: null, certainty: "necunoscut", missing: 1 }]);
    expect(q.value).toBe(2);
    expect(q.missing).toBe(1);
  });
});

describe("manopera, timp, tarif orar implicit", () => {
  it("exemplul din anexa B: 20 doze x 12 lei, 8 min", () => {
    const p = proj();
    // fara alte operatii: dezactivam tot in afara de doze rotunde
    p.library.operations.forEach((o) => (o.active = o.id === "op-doza-rot"));
    const r = p.rooms.find((x) => x.wallTypeId)!;
    for (let i = 0; i < 20; i++) p.boxes.push(box(p, "DA", r.id, "bt-da-rot"));
    const labor = computeLabor(p);
    const line = labor.lines[0];
    expect(line.quantity).toBe(20);
    expect(line.value).toBe(240);
    expect(line.timeMin).toBe(160);
    expect(labor.hours).toBe(2.67);
    expect(labor.impliedHourlyRate).toBe(89.89);
  });
  it("tarif orar implicit null daca timpul este zero", () => {
    const p = proj();
    expect(computeLabor(p).impliedHourlyRate).toBeNull();
  });
  it("factorul de perete beton se aplica explicit pe locasuri", () => {
    const p = proj();
    p.library.operations.forEach((o) => (o.active = o.id === "op-locas"));
    const r = p.rooms[0];
    r.wallTypeId = "wt-beton";
    p.boxes.push(box(p, "DA", r.id, "bt-da-rot"));
    const line = computeLabor(p).lines[0];
    expect(line.allocations[0].factors[0].name).toBe("Perete beton");
    expect(line.value).toBe(16); // 10 lei x 1,6
    expect(line.timeMin).toBe(14.4); // 8 min x 1,8
    expect(line.baseValue).toBe(10);
  });
  it("cantitate manuala suprascrie calculul", () => {
    const p = proj();
    p.library.operations.forEach((o) => (o.active = o.id === "op-doza-rot"));
    p.boxes.push(box(p, "DA", p.rooms[0].id, "bt-da-rot"));
    p.operationOverrides.push({ operationId: "op-doza-rot", enabled: true, quantityOverride: 5, rateOverride: null, timeOverrideMin: null, note: "" });
    const line = computeLabor(p).lines[0];
    expect(line.quantity).toBe(5);
    expect(line.quantitySource).toBe("manual");
    expect(line.value).toBe(60);
  });
  it("fiecare tip de doza are operatia lui de montaj (deviz pe tipuri de doze)", () => {
    const p = proj();
    const r = p.rooms[0].id;
    p.boxes.push(box(p, "DA", r, "bt-da-rot"), box(p, "DA", r, "bt-da-mod4"), box(p, "DD", r, "bt-dd-100"));
    const l = computeLabor(p).lines;
    expect(l.find((x) => x.operation.id === "op-doza-rot")?.quantity).toBe(1);
    expect(l.find((x) => x.operation.id === "op-doza-mod4")?.quantity).toBe(1);
    expect(l.find((x) => x.operation.id === "op-doza-mod")).toBeUndefined();
    expect(l.find((x) => x.operation.id === "op-doza-dd")?.quantity).toBe(1);
  });
});

describe("materiale si total", () => {
  it("materialele sunt separate de manopera; TVA dupa setarea firmei", () => {
    const p = proj();
    const r = p.rooms[0].id;
    p.boxes.push(box(p, "DA", r, "bt-da-rot"));
    const c = circuit(p, 1);
    p.circuits.push(c);
    const m = computeMaterials(p);
    // FY 3x2,5 -> 3 m conductor per metru circuit x 20 m
    expect(m.lines.find((l) => l.materialId === "mat-fy25")?.quantity).toBe(60);
    const t1 = computeTotals(p);
    expect(t1.materials).toBeNull();
    p.quote.includeMaterials = true;
    const t2 = computeTotals(p);
    expect(t2.materials).toBe(m.total);
    expect(t2.vat).toBe(0);
    p.library.firm.vatPayer = true;
    expect(computeTotals(p).vat).toBeGreaterThan(0);
  });
});

describe("export / import", () => {
  it("proiectul se exporta si se reimporta identic", () => {
    const p = proj();
    const r = parseImport(JSON.stringify(projectToFile(p)));
    expect(r.ok).toBe(true);
    if (r.ok && r.kind === "project") {
      expect(r.project.rooms.length).toBe(p.rooms.length);
      expect(r.project.counters).toEqual(p.counters);
    }
  });
  it("biblioteca se exporta si se reimporta", () => {
    const l = lib();
    l.operations[0].rate = 99;
    const r = parseImport(JSON.stringify(libraryToFile(l)));
    expect(r.ok && r.kind === "library" && r.library.operations[0].rate).toBe(99);
  });
  it("respinge fisiere straine sau mai noi", () => {
    expect(parseImport("{}").ok).toBe(false);
    expect(parseImport("nu e json").ok).toBe(false);
    const f = projectToFile(proj());
    f.schemaVersion = 999;
    expect(parseImport(JSON.stringify(f)).ok).toBe(false);
  });
  it("sablon din proiect: date client sterse, structura pastrata", () => {
    const p = proj();
    p.info.client.name = "Client";
    const t = projectAsTemplate(p, 7);
    expect(t.id).not.toBe(p.id);
    expect(t.info.code.endsWith("-007")).toBe(true);
    expect(t.info.client.name).toBe("");
    expect(t.rooms.length).toBe(p.rooms.length);
  });
});
